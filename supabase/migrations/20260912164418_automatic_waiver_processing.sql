create or replace function public.record_waiver_processing_failure(
  p_season_id bigint,
  p_period text,
  p_trigger_source text,
  p_error text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_trigger_source not in ('cron', 'manual') then
    raise exception
      'Invalid waiver trigger source';
  end if;

  insert into public.waiver_processing_runs (
    season_id,
    waiver_period_key,
    status,
    trigger_source,
    attempt_count,
    started_at,
    completed_at,
    result,
    last_error,
    updated_at
  ) values (
    p_season_id,
    p_period,
    'failed',
    p_trigger_source,
    1,
    now(),
    now(),
    '{}'::jsonb,
    left(p_error, 2000),
    now()
  )
  on conflict (
    season_id,
    waiver_period_key
  ) do update
  set status =
      case
        when
          public.waiver_processing_runs.status =
          'completed'
        then 'completed'
        else 'failed'
      end,

      trigger_source =
        excluded.trigger_source,

      attempt_count =
        case
          when
            public.waiver_processing_runs.status =
            'completed'
          then
            public.waiver_processing_runs.attempt_count
          else
            public.waiver_processing_runs.attempt_count + 1
        end,

      completed_at =
        case
          when
            public.waiver_processing_runs.status =
            'completed'
          then
            public.waiver_processing_runs.completed_at
          else
            now()
        end,

      last_error =
        case
          when
            public.waiver_processing_runs.status =
            'completed'
          then
            public.waiver_processing_runs.last_error
          else
            excluded.last_error
        end,

      updated_at = now();
end;
$$;

revoke all on function public.record_waiver_processing_failure(
  bigint,
  text,
  text,
  text
) from public, anon, authenticated;

grant execute on function public.record_waiver_processing_failure(
  bigint,
  text,
  text,
  text
) to service_role;
