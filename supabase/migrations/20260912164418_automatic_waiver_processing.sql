create table if not exists public.waiver_processing_runs (
  id bigint generated by default as identity primary key,
  season_id bigint not null references public.seasons(id) on delete cascade,
  waiver_period_key text not null,
  status text not null check (status in ('running', 'completed', 'failed')),
  trigger_source text not null check (trigger_source in ('cron', 'manual')),
  attempt_count integer not null default 1 check (attempt_count > 0),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  result jsonb not null default '{}'::jsonb,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (season_id, waiver_period_key)
);

alter table public.waiver_processing_runs enable row level security;
revoke all on table public.waiver_processing_runs from anon, authenticated;
grant all on table public.waiver_processing_runs to service_role;
grant usage, select on sequence public.waiver_processing_runs_id_seq to service_role;

create unique index if not exists waiver_transactions_claim_id_key
  on public.waiver_transactions (claim_id)
  where claim_id is not null;

create or replace function public.execute_waiver_transaction(
  p_season_id bigint,
  p_period text,
  p_owner_id bigint,
  p_add_team_id bigint,
  p_drop_team_id bigint,
  p_claim_id bigint,
  p_round integer,
  p_order integer,
  p_competing bigint[],
  p_effective_at timestamptz default now()
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_transaction_id bigint;
  v_roster_slot_id bigint;
  v_claim public.waiver_claims%rowtype;
begin
  select id into v_transaction_id
  from public.waiver_transactions
  where claim_id = p_claim_id;

  if found then
    return v_transaction_id;
  end if;

  select * into v_claim
  from public.waiver_claims
  where id = p_claim_id
  for update;

  if not found
     or v_claim.status <> 'pending'
     or v_claim.season_id <> p_season_id
     or v_claim.waiver_period_key <> p_period
     or v_claim.owner_id <> p_owner_id
     or v_claim.add_team_id <> p_add_team_id
     or v_claim.drop_team_id <> p_drop_team_id then
    raise exception 'Claim is not pending or does not match the transaction';
  end if;

  perform id
  from public.roster_entries
  where season_id = p_season_id
    and team_id = p_add_team_id
  for update;

  if found then
    raise exception 'Add team is already owned';
  end if;

  select roster_slot_id into v_roster_slot_id
  from public.roster_entries
  where season_id = p_season_id
    and owner_id = p_owner_id
    and team_id = p_drop_team_id
  for update;

  if not found then
    raise exception 'Drop team is not on owner roster';
  end if;

  insert into public.waiver_transactions (
    season_id,
    waiver_period_key,
    owner_id,
    add_team_id,
    drop_team_id,
    claim_id,
    waiver_round,
    waiver_order,
    effective_at,
    competing_claim_owner_ids
  ) values (
    p_season_id,
    p_period,
    p_owner_id,
    p_add_team_id,
    p_drop_team_id,
    p_claim_id,
    p_round,
    p_order,
    p_effective_at,
    coalesce(p_competing, '{}'::bigint[])
  )
  returning id into v_transaction_id;

  update public.team_ownership_history
  set released_at = p_effective_at,
      transaction_id = v_transaction_id
  where season_id = p_season_id
    and owner_id = p_owner_id
    and team_id = p_drop_team_id
    and released_at is null;

  update public.roster_entries
  set team_id = p_add_team_id,
      draft_pick = null
  where season_id = p_season_id
    and owner_id = p_owner_id
    and roster_slot_id = v_roster_slot_id;

  insert into public.team_ownership_history (
    season_id,
    owner_id,
    team_id,
    roster_slot_id,
    acquired_at,
    acquisition_type,
    transaction_id
  ) values (
    p_season_id,
    p_owner_id,
    p_add_team_id,
    v_roster_slot_id,
    p_effective_at,
    'waiver',
    v_transaction_id
  );

  update public.waiver_claims
  set status = 'successful',
      failure_reason = null,
      processed_at = p_effective_at,
      updated_at = p_effective_at
  where id = p_claim_id;

  return v_transaction_id;
end;
$$;

