create table if not exists public.wheel_entries (
  id bigint generated by default as identity primary key,
  season_id bigint not null
    references public.seasons(id)
    on delete cascade,
  item_text text not null
    check (char_length(btrim(item_text)) between 2 and 160),
  submitted_by uuid not null,
  submitted_by_owner_id bigint
    references public.owners(id)
    on delete set null,
  status text not null default 'pending'
    check (
      status in (
        'pending',
        'approved',
        'rejected',
        'selected'
      )
    ),
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  rejected_at timestamptz,
  selected_at timestamptz,
  constraint wheel_entries_submitted_by_fkey
    foreign key (submitted_by)
    references public.user_profiles(user_id)
    on delete cascade
);

create table if not exists public.wheel_draws (
  id bigint generated by default as identity primary key,
  season_id bigint not null
    references public.seasons(id)
    on delete cascade,
  draw_key text not null,
  week_label text not null,
  selected_entry_id bigint not null
    references public.wheel_entries(id),
  selected_text text not null,
  entry_snapshot jsonb not null,
  drawn_at timestamptz not null default now(),
  unique (season_id, draw_key),
  check (jsonb_typeof(entry_snapshot) = 'array')
);

create table if not exists public.wheel_views (
  draw_id bigint not null
    references public.wheel_draws(id)
    on delete cascade,
  user_id uuid not null
    references public.user_profiles(user_id)
    on delete cascade,
  viewed_at timestamptz not null default now(),
  primary key (draw_id, user_id)
);

create index if not exists wheel_entries_season_status_idx
  on public.wheel_entries(
    season_id,
    status,
    approved_at
  );

create index if not exists wheel_entries_submitter_idx
  on public.wheel_entries(
    submitted_by,
    created_at desc
  );

create index if not exists wheel_draws_season_drawn_idx
  on public.wheel_draws(
    season_id,
    drawn_at desc
  );

create index if not exists wheel_entries_owner_idx
  on public.wheel_entries(
    submitted_by_owner_id
  );

create index if not exists wheel_views_user_idx
  on public.wheel_views(user_id);

