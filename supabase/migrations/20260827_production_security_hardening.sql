DROP POLICY IF EXISTS profiles_insert_self
ON public.user_profiles;

CREATE POLICY profiles_insert_self
ON public.user_profiles
FOR INSERT
TO authenticated
WITH CHECK (
  auth.uid() = user_id
  AND owner_id IS NULL
  AND role = 'owner'::text
);

DROP POLICY IF EXISTS profiles_update_self_username
ON public.user_profiles;

CREATE POLICY profiles_update_self_username
ON public.user_profiles
FOR UPDATE
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (
  auth.uid() = user_id
  AND NOT (
    owner_id IS DISTINCT FROM (
      SELECT p.owner_id
      FROM public.user_profiles p
      WHERE p.user_id = auth.uid()
    )
  )
  AND NOT (
    role IS DISTINCT FROM (
      SELECT p.role
      FROM public.user_profiles p
      WHERE p.user_id = auth.uid()
    )
  )
);

